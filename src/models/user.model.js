import mongoose from "mongoose";

// Como lo voy a guardar
const userSchema = new mongoose.Schema({
    username: {
        type: String,
        required: true,
        trim: true
    },
    email: {
        type: String,
        required: true,
        trim: true,
        unique: true
    },
    password: {
        type: String,
        required: true
    },
    firstName: {
        type: String,
        trim: true,
        required: true
    },
    lastName: {
        type: String,
        trim: true,
        required: true
    }
}, {
    timestamps: true
})

// Para interactuar con los métodos
export default mongoose.model('User', userSchema)